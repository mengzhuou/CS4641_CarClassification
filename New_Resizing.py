import os
import shutil

def merge_train_and_test_sets(merged_dir, train_root, test_root):
    """
    Merges matching car model folders from train and test directories into a new directory.
    If a car model exists in both train and test, combines all images.

    Args:
      merged_
    """
    # Make sure the merged directory exists
    os.makedirs(merged_dir, exist_ok=True)

    for car in os.listdir(train_root):
        train_model_path = os.path.join(train_root, car)
        merged_model_path = os.path.join(merged_dir, car)
        if not os.path.exists(merged_model_path):
          shutil.copytree(train_model_path, merged_model_path, dirs_exist_ok=True)
        else:
          print(f"{car} already copied over.")

    for car in os.listdir(test_root):
        test_model_path = os.path.join(test_root, car)
        merged_model_path = os.path.join(merged_dir, car)

        if os.path.exists(merged_model_path):
            for filename in os.listdir(test_model_path):
                test_file_path = os.path.join(test_model_path, filename)
                merged_file_path = os.path.join(merged_model_path, filename)

                if not os.path.exists(merged_file_path):
                    shutil.copy2(test_file_path, merged_model_path)
    print("Done with entire merge.")

