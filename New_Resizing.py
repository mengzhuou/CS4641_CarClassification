from PIL import Image, ImageOps
import os
import numpy as np
import matplotlib.pyplot as plt

train_dir = "/content/train"
test_dir = "/content/test"

def find_median(image_dir):
    widths = []
    heights = []
    for folder_name in os.listdir(image_dir):
        folder_path = os.path.join(image_dir, folder_name)
        if os.path.isdir(folder_path):
            for image_name in os.listdir(folder_path):
                image_path = os.path.join(folder_path, image_name)
                try:
                    with Image.open(image_path) as img:
                        widths.append(img.width)
                        heights.append(img.height)
                except Exception as e:
                    print(f"Error processing {image_path}: {e}")

    median_width = int(np.median(widths))
    median_height = int(np.median(heights))
    print(f"Rounded median height and width: ({median_width}, {median_height})")

    return (median_width, median_height)

optimal_size = find_median(train_dir)

def resize_images(image_dir, target_size):
    resized_images = {}
    for folder_name in os.listdir(image_dir):
        folder_path = os.path.join(image_dir, folder_name)
        if os.path.isdir(folder_path):
            for image_name in os.listdir(folder_path):
                image_path = os.path.join(folder_path, image_name)
                try:
                    with Image.open(image_path) as img:
                        current_size = img.size
                        if current_size != target_size:
                            # Resize with aspect ratio
                            img.thumbnail(target_size, Image.LANCZOS)

                            # padding, differentiate for different channels
                            if img.mode == "RGB":
                                padding_color = (255, 255, 255)
                            elif img.mode == "L":
                                padding_color = 255  # grayscale
                            else:
                                print(f"Image's mode {img.mode} for image {image_name} is unsupported. Skipping...")
                                continue

                            img_padded = ImageOps.pad(img, target_size, color=padding_color)
                            img_padded.save(image_path)
                            resized_images[image_name] = current_size
                except Exception as e:
                    print(f"Error processing {image_path}: {e}")
    return resized_images

print("Resizing train and test dataset:")
