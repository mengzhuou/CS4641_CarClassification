def check_image_count(merged_dir, train_dir, test_dir):
    num_merged = len([name for name in os.listdir(merged_dir) if os.path.isfile(os.path.join(merged_dir, name))])

    if os.path.exists(test_dir):
        num_test = len([name for name in os.listdir(test_dir) if os.path.isfile(os.path.join(test_dir, name))])
    else:
        num_test = 0  # Set to 0 if the test directory doesn't exist
    if os.path.exists(train_dir):
        num_train = len([name for name in os.listdir(train_dir) if os.path.isfile(os.path.join(train_dir, name))])
    else:
        num_train = 0  # Set to 0 if the train directory doesn't exist

    if not (num_merged == (num_test + num_train)):
      print(f"Mismatch with {merged_dir}")
      print(f"Merged: {num_merged}, Test: {num_test}, Train: {num_train}")
    return num_merged == (num_test + num_train)


def check_all_car_types(merged_root, train_root, test_root):
    """
    Checks if the image count for every car model in merged_dir matches
    the combined count from train_dir and test_dir.

    Parameters:
    merged_root (str): Path to the root directory where merged car model folders are stored.
    test_root (str): Path to the root directory where test car model folders are stored.
    train_root (str): Path to the root directory where train car model folders are stored.

    Returns:
    bool: True if all car model counts match, False if any discrepancy is found.
    """
    car_models = set(os.listdir(train_root)) | set(os.listdir(test_root))
    all_counts_match = True

    for car_model in car_models:
        merged_dir = os.path.join(merged_root, car_model)
        train_dir = os.path.join(train_root, car_model)
        test_dir = os.path.join(test_root, car_model)

        if os.path.exists(merged_dir):
            if not check_image_count(merged_dir, train_dir, test_dir):
                print(f"Mismatch in image count for {car_model}")
                all_counts_match = False
        else:
            print(f"{car_model} does not exist in the merged directory.")
            all_counts_match = False

    return True

