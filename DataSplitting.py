import os
import shutil
import random

def split_dataset(merged_root, split_root, train_ratio=0.8, test_ratio=0.1, val_ratio=0.1):
    train_dir = os.path.join(split_root, "new_train")
    test_dir = os.path.join(split_root, "new_test")
    val_dir = os.path.join(split_root, "validation")

    os.makedirs(train_dir, exist_ok=True)
    os.makedirs(test_dir, exist_ok=True)
    os.makedirs(val_dir, exist_ok=True)

    for car in os.listdir(merged_root):
        car_path = os.path.join(merged_root, car)
        images = os.listdir(car_path)
        random.shuffle(images)

        total_images = len(images)
        train_count = int(total_images * train_ratio)
        test_count = int(total_images * test_ratio)

        train_images = images[:train_count]
        test_images = images[train_count:train_count + test_count]
        val_images = images[train_count + test_count:]

        for curr_dir, curr_images in zip([train_dir, test_dir, val_dir], [train_images, test_images, val_images]):
            curr_path = os.path.join(curr_dir, car)
            os.makedirs(curr_path, exist_ok=True)
            for image in curr_images:
                source_path = os.path.join(car_path, image)
                dest_path = os.path.join(curr_path, image)
                if not os.path.exists(dest_path):
                  shutil.copy2(source_path, dest_path)

    print("Dataset fully split into training, testing, and validation sets.")

split_dataset(merged_root, split_root, train_ratio=0.8, test_ratio=0.1, val_ratio=0.1)

